import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const w={};w.window=w;
vm.runInNewContext(readFileSync('frontend/station-workspace.js','utf8'),{window:w});
const {register,route,StationWorkspace}=w.StationWorkspace;
assert.equal(register('c'),'C');
assert.equal(register('D'),'D');
assert.equal(route('C','/api/flows'),'/api/stations/C/flows');
assert.equal(route('D','/api/audit?page=1'),'/api/stations/D/audit?page=1');
assert.throws(()=>register('../unsafe'));
assert.throws(()=>register('bad/name'));
assert.throws(()=>register('bad'.repeat(7)));
const space=new StationWorkspace('A');const stale=space.context();space.select('D');assert(!space.isCurrent(stale));
