import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const cfg=JSON.parse(fs.readFileSync(new URL('../backend/DeviceControl.Api/config/station.json',import.meta.url),'utf8'));
const saved=new Map();
const ctx={window:{STATION_CONFIG:structuredClone(cfg)},localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)},setTimeout,clearTimeout,Date,Promise,Error,structuredClone,console};
vm.createContext(ctx);
for(const f of ['shared-resource-coordinator.js','workflow-engine.js','mock-runtime.js','workflow-studio.js','workflow-edit-history.js','workflow-replay.js'])vm.runInContext(fs.readFileSync(new URL('../frontend/'+f,import.meta.url),'utf8'),ctx);
const {EditHistory,cloneFresh,allIds,diffFlows}=ctx.window.WorkflowEditTools;
const source=structuredClone(cfg.sequence),history=new EditHistory(source,3);
assert.equal(history.changed,false);
assert(!history.undo());
history.transact(nodes=>nodes[0].label='标签 A');assert(history.changed);
history.transact(nodes=>nodes[0].label='标签 B');
assert(history.undo());assert.equal(history.present[0].label,'标签 A');
assert(history.redo());assert.equal(history.present[0].label,'标签 B');
assert(history.undo());history.transact(nodes=>nodes[0].label='标签 C');assert.equal(history.canRedo,false,'new edit must invalidate redo');
assert(history.undo());assert(history.undo());assert.equal(history.changed,false,'undo back to baseline clears dirty');
for(let i=0;i<6;i++)history.transact(n=>n[0].label='label-'+i);
assert.equal(history.past.length,3,'undo history must be bounded');
const parallel=source.find(x=>x.type==='Parallel');assert(parallel);
const copy=cloneFresh(parallel,allIds(source));assert.notEqual(copy.id,parallel.id);
assert(copy.children.every(c=>!allIds(source).has(c.id)),'children must receive new IDs');
const cloneAgain=cloneFresh(parallel,allIds([...source,copy]));assert.notEqual(cloneAgain.id,copy.id);
const changed=structuredClone(source);changed.splice(1,0,copy);changed[0].label='已修改';
const diff=diffFlows(source,changed);assert(diff.added.length>=3);assert(diff.changed.some(x=>x.id===source[0].id));assert(diff.moved.length>0);
assert.equal(ctx.window.FlowStudioModel.validateFlow(changed,cfg).length,0);
const fake={id:'run-01',flowVersion:'flow-0003',outcome:'Completed',steps:[{index:0,label:'汇总步骤',outcome:'Completed',durationMs:8}]};
const replay=ctx.window.WorkflowReplay.timeline(fake);
assert.equal(replay.length,1);assert.equal(replay[0].vars,null,'step aggregate cannot invent variables');
const annotated={...fake,trace:[{id:'vision',label:'检测',type:'VisionLocate',durationMs:7,status:'Completed',variablesAfter:{'Vision.OK':true,'Vision.TargetXmm':80}}]};
const captured=ctx.window.WorkflowReplay.timeline(annotated);assert.equal(captured[0].vars['Vision.TargetXmm'],80);
captured[0].vars['Vision.TargetXmm']=999;assert.equal(annotated.trace[0].variablesAfter['Vision.TargetXmm'],80,'replay must not mutate history');
const machine=new ctx.window.MockRuntime();assert.equal(machine.traceVariables()['Axis.X'],cfg.axes[0].homeMm);
assert.equal(machine.traceVariables()['DI.PartPresent'],true);
console.log('PASS V0.7 primitives: bounded undo/redo, dirty reset, copy unique nested IDs, version diff, replay factual variables');
