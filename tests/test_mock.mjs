import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const cfg=JSON.parse(fs.readFileSync(new URL('../backend/DeviceControl.Api/config/station.json',import.meta.url),'utf8'));
const ctx={window:{STATION_CONFIG:cfg},setTimeout,clearTimeout,console,Date,Error,Promise};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../frontend/shared-resource-coordinator.js',import.meta.url),'utf8'),ctx);
vm.runInContext(fs.readFileSync(new URL('../frontend/workflow-engine.js',import.meta.url),'utf8'),ctx);
vm.runInContext(fs.readFileSync(new URL('../frontend/mock-runtime.js',import.meta.url),'utf8'),ctx);
const m=new ctx.window.MockRuntime();
const p=(path,body)=>m.post(path,body);
const delay=ms=>new Promise(r=>setTimeout(r,ms));
async function until(predicate,ms=9000){const start=Date.now();while(!predicate()){if(Date.now()-start>ms)throw Error('timeout waiting for simulation');await delay(50)}}
assert.equal(Object.keys(m.snapshot().axes).length,2);
assert.equal(Object.keys(m.snapshot().cylinders).length,2);
assert.equal(Object.keys(m.snapshot().outputs).length,4);
assert.equal(cfg.sequence.length,9);
await assert.rejects(p('/api/sim/input',{name:'ClampExtended',value:true}),/不可修改/);
await assert.rejects(p('/api/cycle/start'),/自动模式/);
for(const axis of ['X','Y']){
  await p(`/api/manual/axes/${axis}/enable`,{enabled:true});
  await p(`/api/manual/axes/${axis}/home`);
  assert(m.snapshot().axes[axis].homed);
}
await assert.rejects(p('/api/manual/cylinders/Clamp/extend'),/阻挡气缸必须伸出/);
assert.equal(m.snapshot().state,'Idle');
await p('/api/manual/cylinders/Stopper/extend');
await assert.rejects(p('/api/manual/axes/X/move',{positionMm:40}),/阻挡气缸必须缩回/);
await p('/api/manual/cylinders/Clamp/extend');
assert.equal(m.snapshot().cylinders.Clamp.position,'Extended');
await p('/api/manual/cylinders/Clamp/retract');
await p('/api/manual/cylinders/Stopper/retract');
await p('/api/manual/axes/Y/move',{positionMm:20});
assert.equal(m.snapshot().axes.Y.positionMm,20);
await p('/api/manual/axes/Y/move',{positionMm:0});
await assert.rejects(p('/api/manual/axes/Y/move',{positionMm:180}),/超出行程/);
// Out-of-range movement is rejected by an actuator and puts the station in recoverable fault.
assert.equal(m.snapshot().state,'Fault');
await p('/api/fault/reset');
for(const axis of ['X','Y'])await p(`/api/manual/axes/${axis}/home`);
await p('/api/recovery/confirm');
await p('/api/mode',{mode:'Auto'});
await p('/api/cycle/start');
await until(()=>!m.snapshot().busy);
assert.equal(m.snapshot().cycles,1);
assert.equal(m.snapshot().cycleHistory.length,1);
assert.equal(m.snapshot().cycleHistory[0].outcome,'Completed');
assert.equal(m.snapshot().cycleHistory[0].steps.length,13);
assert(m.snapshot().cycleHistory[0].durationMs>0);
assert(m.snapshot().stepHistory.every(s=>s.durationMs>=0));
assert.equal(m.snapshot().state,'Idle');
assert.equal(m.snapshot().cylinders.Stopper.position,'Retracted');
assert.equal(m.snapshot().axes.X.positionMm,0);
await p('/api/sim/fault',{name:'ClampStuck',value:true});
await p('/api/cycle/start');
await until(()=>!m.snapshot().busy);
assert.equal(m.snapshot().state,'Fault');
assert.match(m.snapshot().alarm,/超时/);
assert.equal(m.snapshot().cycleHistory[0].outcome,'Failed');
assert.equal(m.snapshot().activeAlarm.code,'ACT-CYL-TIMEOUT');
assert(m.snapshot().activeAlarm.suggestion.length>10);
assert(m.snapshot().cycleHistory[0].steps.some(s=>s.outcome==='Failed'));
assert.equal(m.snapshot().recoveryRequired,true);
assert.equal(m.snapshot().outputs.ClampExtend,false);
await p('/api/sim/fault',{name:'ClampStuck',value:false});
await p('/api/fault/reset');
await assert.rejects(p('/api/recovery/confirm'),/尚未/);
await p('/api/manual/cylinders/Clamp/retract');
await p('/api/manual/cylinders/Stopper/retract');
for(const axis of ['X','Y'])await p(`/api/manual/axes/${axis}/home`);
await p('/api/recovery/confirm');
await p('/api/mode',{mode:'Auto'});
await p('/api/cycle/start');
await delay(380);
await p('/api/cycle/stop');
await until(()=>!m.snapshot().busy);
assert.equal(m.snapshot().state,'Idle');
assert.equal(m.snapshot().recoveryRequired,true);
assert.equal(m.snapshot().cycleHistory[0].outcome,'Stopped');
assert.equal(m.snapshot().cycleHistory.length,3);
await assert.rejects(p('/api/mode',{mode:'Auto'}),/恢复确认/);
console.log('PASS V0.3 mock tests: multiple devices, IO whitelist, interlocks, motion bounds, full cycle, cylinder timeout, reset/recovery, stop');
