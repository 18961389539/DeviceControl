"""V1.6 real offline Chromium gates: no evidence -> no rollout expansion;
actual simulation cycles, station isolation and staged waves. No .NET tested."""
import asyncio,shutil
from pathlib import Path
from playwright.async_api import async_playwright
ROOT=Path(__file__).resolve().parents[1]
async def run():
 async with async_playwright() as pw:
  opts={'headless':True,'args':['--no-sandbox']}
  if shutil.which('chromium'):opts['executable_path']=shutil.which('chromium')
  browser=await pw.chromium.launch(**opts)
  page=await browser.new_page(viewport={'width':1600,'height':960})
  errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  await page.set_content((ROOT/'tests'/'fixtures'/'DeviceControl_V1.7_Preview.html').read_text(encoding='utf8'),wait_until='load')
  await page.locator('#loginUser').select_option('admin');await page.locator('#loginForm button').click()
  await page.locator('#loginOverlay').wait_for(state='hidden')
  await page.locator('[data-tab=templates]').click()
  await page.locator('#templateName').fill('V16 standard')
  await page.locator('[data-template-action=capture]').click()
  await page.wait_for_function("() => document.getElementById('templateSummary').textContent.includes('Draft')")
  await page.locator('[data-template-action=validate]').click()
  await page.wait_for_function("() => document.getElementById('templateSummary').textContent.includes('Validated')")
  await page.locator('[data-template-action=publish]').click()
  await page.wait_for_function("() => document.getElementById('templateSummary').textContent.includes('Published')")
  await page.locator('#rolloutIds').fill('A,B')
  await page.locator('[data-rollout=create]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('PilotPending')")
  await page.locator('[data-rollout=advance]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('AwaitingEvidence')",timeout=10000)
  assert 'AwaitingEvidence' in await page.locator('#rolloutSteps').inner_text()
  assert 'Pending' in await page.locator('#rolloutSteps').inner_text()
  assert await page.locator('[data-rollout=advance]').is_disabled()
  await page.locator('[data-rollout=verify]').click()
  await page.wait_for_function("() => document.getElementById('rolloutMessage').textContent.includes('缺少升级后的合格仿真周期')",timeout=6000)
  async def complete(station):
   await page.locator('#workspaceStation').select_option(station)
   await page.wait_for_function("s => document.getElementById('workspaceTag').textContent==='工作区 '+s",arg=station)
   await page.locator('.navigation [data-tab=manual]').click()
   for axis in ['X','Y']:
    await page.locator('#axisSelect').select_option(axis)
    await page.locator('[data-action=servo-on]').click()
    await page.locator('[data-action=axis-home]').click()
    await page.wait_for_timeout(950)
   await page.locator('[data-tab=dashboard]').click()
   await page.locator('[data-mode=Auto]').click()
   await page.wait_for_function("() => document.getElementById('modeValue').textContent==='自动'",timeout=6000)
   await page.locator('[data-action=cycle-start]').click()
   await page.wait_for_function("() => Number(document.getElementById('cyclesValue').textContent)>=1",timeout=30000)
   await page.wait_for_function("() => document.getElementById('stateValue').textContent==='待机'",timeout=12000)
   await page.locator('[data-mode=Manual]').click()
   await page.wait_for_function("() => document.getElementById('modeValue').textContent==='手动'",timeout=6000)
   await page.locator('[data-tab=templates]').click()
  await complete('A')
  await page.locator('[data-rollout=inspect]').click()
  await page.wait_for_function("() => document.getElementById('rolloutMessage').textContent.includes('证据齐全')",timeout=7000)
  await page.locator('[data-rollout=verify]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('WaveReady')",timeout=7000)
  await page.locator('[data-rollout=advance]').click()
  await page.wait_for_function("() => document.querySelectorAll('.rollout-step .rollout-state')[1]?.textContent==='AwaitingEvidence'",timeout=7000)
  await page.locator('[data-rollout=pause]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('Paused')")
  assert await page.locator('[data-rollout=verify]').is_disabled()
  await page.locator('[data-rollout=resume]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('AwaitingEvidence')")
  await complete('B')
  await page.locator('[data-rollout=verify]').click()
  await page.wait_for_function("() => document.getElementById('rolloutProgress').textContent.includes('Completed')",timeout=7000)
  assert await page.locator('[data-rollout=advance]').is_disabled()
  assert '已验收 2 / 2' in await page.locator('#rolloutProgress').inner_text()
  await page.screenshot(path=str(ROOT/'DeviceControl_V1.6_Rollout.png'),full_page=True)
  assert not errors,errors
  await browser.close()
  print('PASS V1.6 Chromium: pilot evidence gate, actual cycles A/B, phased wave, pause/resume, complete')
if __name__=='__main__':asyncio.run(run())
