#!/usr/bin/env python3
"""V2.0 release manifest: hash the delivery scope of the current source revision.

Q08: the top-level MANIFEST_SHA256.txt and DeviceControl_V2.0_ReleaseStatus.json
must describe the SAME revision that is being delivered. This tool

- `--write`           regenerates MANIFEST_SHA256.txt from the current worktree;
- `--verify`          fails (exit 1 + RESULT: FAIL) on any missing, changed or
                      unregistered delivery file, so a release can never be based
                      on stale evidence; a strict release gate runs this task;
- `--bind-status GATE` writes DeviceControl_V2.0_ReleaseStatus.json bound to the
                      current git revision, the manifest digest and the given
                      release-gate JSON evidence.

Delivery scope: source, configuration, tests, tools, docs and CI files that are
tracked as project content. Generated artifacts are intentionally excluded:
directories (artifacts/, reports/, bin/, obj/, runtime data/), the regenerated
browser preview fixtures, the root-level browser-regression screenshots
(rewritten by the Chromium tests on every run) and the two generated evidence
files (manifest + release status). The gate's offline:preview-build task
rewrites the fixtures during a release run.
"""
import argparse
import datetime as dt
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'MANIFEST_SHA256.txt'
STATUS = ROOT / 'DeviceControl_V2.0_ReleaseStatus.json'

EXCLUDE_DIRS = {'artifacts', 'reports', '.git', '.workbuddy', 'bin', 'obj',
                'node_modules', '__pycache__', '.venv', 'venv'}
EXCLUDE_FILES = {'MANIFEST_SHA256.txt', 'DeviceControl_V2.0_ReleaseStatus.json',
                 '.DS_Store'}
EXCLUDE_PREFIXES = ('tests/fixtures/',)
EXCLUDE_SUFFIXES = ('.pyc', '.pyo', '.tmp')


def _fallback_files():
    import os
    files = []
    for root, dirs, names in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in EXCLUDE_DIRS)
        for name in names:
            files.append((Path(root) / name).relative_to(ROOT).as_posix())
    return files


def delivery_files():
    """Delivery scope = the git delivery set (tracked + untracked-not-ignored) minus
    generated evidence directories and the two generated evidence files. This keeps
    ignored runtime data (data/, bin/, obj/) out and covers newly added source files."""
    try:
        result = subprocess.run(['git', 'ls-files', '--cached', '--others', '--exclude-standard', '-z'],
                                cwd=ROOT, capture_output=True, timeout=60)
        candidates = [x.decode('utf-8', 'replace') for x in result.stdout.split(b'\0') if x] \
            if result.returncode == 0 else _fallback_files()
    except Exception:
        candidates = _fallback_files()
    files = []
    for rel in candidates:
        rel = rel.replace('\\', '/')
        if not (ROOT / rel).is_file():
            continue  # index entry without a worktree file (pending deletion)
        segments = rel.split('/')
        if any(seg in EXCLUDE_DIRS for seg in segments[:-1]):
            continue
        if rel.startswith(EXCLUDE_PREFIXES) or segments[-1] in EXCLUDE_FILES:
            continue
        if segments[-1].endswith(EXCLUDE_SUFFIXES):
            continue
        if '/' not in rel and rel.lower().endswith('.png'):
            continue  # root-level browser-regression screenshots are regenerated by the gate
        files.append(rel)
    return sorted(files)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_manifest():
    recorded = {}
    if MANIFEST.exists():
        for line in MANIFEST.read_text(encoding='utf-8').splitlines():
            match = re.match(r'^([0-9a-fA-F]{64})\s+\*?(.+)$', line.strip())
            if match:
                recorded[match.group(2).strip()] = match.group(1).lower()
    return recorded


def write_manifest():
    entries = {rel: digest(ROOT / rel) for rel in delivery_files()}
    MANIFEST.write_text(''.join(f'{h}  {rel}\n' for rel, h in sorted(entries.items())),
                        encoding='utf-8')
    print(f'RESULT: PASS manifest written: {len(entries)} entries, sha256={digest(MANIFEST)[:16]}')
    return entries


def verify_manifest():
    if not MANIFEST.exists():
        print('RESULT: FAIL manifest missing: run tools/release_manifest.py --write')
        return 1
    recorded = read_manifest()
    current = {rel: digest(ROOT / rel) for rel in delivery_files()}
    missing = sorted(set(recorded) - set(current))
    unregistered = sorted(set(current) - set(recorded))
    changed = sorted(rel for rel in set(recorded) & set(current) if recorded[rel] != current[rel])
    if missing or unregistered or changed:
        for rel in missing[:20]:
            print(f'  missing     {rel}')
        for rel in changed[:20]:
            print(f'  mismatched  {rel}')
        for rel in unregistered[:20]:
            print(f'  unregistered {rel}')
        print(f'RESULT: FAIL manifest does not describe the current revision '
              f'(missing={len(missing)} mismatched={len(changed)} unregistered={len(unregistered)}); '
              f'regenerate with --write after the delivery is frozen')
        return 1
    print(f'RESULT: PASS manifest verified: {len(current)} entries, zero missing/mismatch/unregistered')
    return 0


def git_revision():
    try:
        head = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT,
                              capture_output=True, text=True, timeout=30).stdout.strip()
        dirty = bool(subprocess.run(['git', 'status', '--porcelain'], cwd=ROOT,
                                    capture_output=True, text=True, timeout=30).stdout.strip())
        return head or 'unknown', dirty
    except Exception:
        return 'unknown', None


def bind_status(gate_path):
    gate = json.loads(Path(gate_path).read_text(encoding='utf-8'))
    if not MANIFEST.exists():
        print('RESULT: FAIL manifest missing; run --write before binding the status')
        return 1
    head, dirty = git_revision()
    worktree_digest = hashlib.sha256(
        ''.join(f'{rel} {digest(ROOT / rel)}\n' for rel in delivery_files()).encode('utf-8')).hexdigest()
    passed = gate.get('passed', 0); failed = gate.get('failed', 0); blocked = gate.get('blocked', 0)
    approved = bool(gate.get('releaseApproved'))
    status = {
        'version': '2.0-rc',
        'generatedAtUtc': dt.datetime.now(dt.timezone.utc).isoformat(),
        'releaseApproved': approved,
        'fullReleaseGateExecuted': gate.get('profile') == 'release' and bool(gate.get('tests')),
        'dotnetSdkAvailable': bool(gate.get('dotnetPresent')),
        'sourceRevision': {'gitHead': head, 'workingTreeDirty': dirty, 'worktreeDigest': worktree_digest},
        'manifest': {'file': MANIFEST.name, 'sha256': digest(MANIFEST),
                     'entries': len(read_manifest())},
        'gateEvidence': {'path': str(Path(gate_path)), 'profile': gate.get('profile'),
                         'passed': passed, 'failed': failed, 'blocked': blocked,
                         'dotnetPresent': bool(gate.get('dotnetPresent')),
                         'startedUtc': gate.get('startedUtc'), 'finishedUtc': gate.get('finishedUtc')},
        'reason': ('full release profile executed; release approved'
                   if approved else
                   f'release NOT approved: {failed} failed / {blocked} blocked task(s) '
                   f'under the strict Q07 status contract' if gate.get('profile') == 'release'
                   else 'release profile not executed; do not treat offline diagnostics as approval'),
        'note': ('Software-only simulation. Status is bound to the revision, manifest digest and '
                 'gate evidence above; any source change invalidates it until regenerated.')
    }
    STATUS.write_text(json.dumps(status, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'RESULT: PASS release status bound: head={head[:10]} dirty={dirty} '
          f'approved={approved} evidence={gate_path}')
    return 0


def main():
    parser = argparse.ArgumentParser(description='V2.0 release manifest and status binder')
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true', help='regenerate MANIFEST_SHA256.txt')
    mode.add_argument('--verify', action='store_true', help='verify the manifest against the worktree')
    mode.add_argument('--bind-status', metavar='GATE_JSON', help='bind ReleaseStatus to gate evidence')
    args = parser.parse_args()
    if args.write:
        write_manifest()
        return 0
    if args.verify:
        return verify_manifest()
    return bind_status(args.bind_status)


if __name__ == '__main__':
    sys.exit(main())
